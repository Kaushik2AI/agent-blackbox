"""Versioned fixture tasks. Each fixture is an immutable JSON file in ./fixtures/.

`ground_truth` is what a CORRECT agent would leave in the sandbox; the verifier checks
the final sandbox against it. `expected_baseline` records how the stock (scripted) agent
is known to behave on this fixture; tests use it to prove failures happen for the
intended reason. Neither is ever shown to the agent.
"""

from __future__ import annotations

import hashlib
import json
from functools import cache
from importlib import resources
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field

Termination = Literal["completed", "budget_exhausted", "tool_failure", "error"]


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class Task(_Strict):
    customer_id: str
    order_id: str
    request: Literal["exchange", "refund"]
    message: str


class ModelScript(_Strict):
    """Behaviour knobs for the deterministic stub model (see model.py)."""

    inventory_argument: Literal["sku", "product_name"] = "sku"
    max_retries_on_timeout: int = Field(default=2, ge=0)
    resolution_order_id: str | None = None
    # "lower": the model writes the order id in lower case ("ord-1001"), the lookup
    # rejects it and the naive retry policy loops (benchmark family "repeat_loop").
    order_id_case: Literal["lower"] | None = None


class Budget(_Strict):
    max_tool_calls: int = Field(ge=1)


class Resolution(_Strict):
    order_id: str
    choice: Literal["exchange", "refund"]


class GroundTruth(_Strict):
    resolution: Resolution
    draft_customer_id: str


class ExpectedBaseline(_Strict):
    verifier_passed: bool
    termination: Termination
    error_codes: list[str]


class Fixture(_Strict):
    fixture_id: str
    fixture_version: str
    description: str
    task: Task
    world: dict[str, Any]
    faults: dict[str, int]
    model: ModelScript
    budget: Budget
    ground_truth: GroundTruth
    expected_baseline: ExpectedBaseline

    @property
    def content_hash(self) -> str:
        """SHA-256 of the canonical fixture JSON: identifies exactly what was run."""
        data = self.model_dump(mode="json")
        # Knobs added after v1.0 are left out while unset, so the hash of every existing
        # fixture (and therefore every saved checkpoint) stays valid.
        if data["model"].get("order_id_case") is None:
            data["model"].pop("order_id_case", None)
        canonical = json.dumps(data, sort_keys=True).encode()
        return hashlib.sha256(canonical).hexdigest()


def _fixture_files() -> dict[str, Any]:
    root = resources.files("agent_harness") / "fixtures"
    return {p.name.removesuffix(".json"): p for p in root.iterdir() if p.name.endswith(".json")}


def list_fixtures() -> list[str]:
    """The hand-written demo fixtures (benchmark cases are listed by benchmark_cases)."""
    return sorted(_fixture_files())


class BenchmarkCase(_Strict):
    """One benchmark case: a generated fixture plus how it is used in evaluation."""

    case_id: str
    benchmark_version: str
    family: str
    split: Literal["dev", "heldout"]
    expected_findings: list[str]
    fixture: Fixture


@cache
def benchmark_cases(version: str = "benchmark_v1") -> tuple[BenchmarkCase, ...]:
    """Versioned benchmark cases shipped with the harness (generated by
    `python -m evaluation.dataset`, committed, and checked for drift by tests)."""
    path = resources.files("agent_harness") / "benchmarks" / f"{version}.jsonl"
    if not path.is_file():
        return ()
    lines = [ln for ln in path.read_text().splitlines() if ln.strip()]
    return tuple(BenchmarkCase.model_validate_json(ln) for ln in lines)


@cache
def load_fixture(fixture_id: str) -> Fixture:
    files = _fixture_files()
    if fixture_id in files:
        fixture = Fixture.model_validate_json(files[fixture_id].read_text())
        if fixture.fixture_id != fixture_id:
            raise ValueError(f"{fixture_id}.json declares fixture_id={fixture.fixture_id!r}")
        return fixture
    # Benchmark cases are resolvable by id too, so their runs can be replayed in the app.
    for case in benchmark_cases():
        if case.fixture.fixture_id == fixture_id:
            return case.fixture
    raise KeyError(f"unknown fixture {fixture_id!r}; available: {', '.join(sorted(files))}")
