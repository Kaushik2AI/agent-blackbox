#!/usr/bin/env bash
# One-time setup of Agent BlackBox on BU SCC (or any Linux box) using ONLY Python + pip.
# No conda, no Docker, no root.
#
# What it does:
#   1. Creates a Python venv at .venv (Python 3.11 or 3.12).
#   2. pip-installs the API plus PostgreSQL 16, Redis 6.2 and Node 22, which ship as
#      Python wheels (see infra/scc/requirements-local-services.txt), and links their
#      binaries into .venv/bin.
#   3. npm-installs the web app.
#   4. Writes .env with RANDOM passwords and per-user ports (SCC compute nodes are
#      shared, so default ports like 5432 may already be taken by someone else).
#   5. Initialises a password-protected Postgres cluster, creates the DB, runs migrations.
#
# Run from the repo root inside an OnDemand session (VS Code / Desktop), NOT a login node:
#     make setup-scc          (or: bash infra/scc/setup_scc.sh)
# Safe to re-run: every step skips work that is already done.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$REPO_ROOT"

ENV_FILE="$REPO_ROOT/.env"
# Values already saved in .env (e.g. BLACKBOX_VENV) win over defaults on re-runs.
if [ -z "${BLACKBOX_VENV:-}" ] && [ -f "$ENV_FILE" ]; then
  BLACKBOX_VENV="$(sed -n 's/^BLACKBOX_VENV=//p' "$ENV_FILE" | tail -1)"
fi
VENV="${BLACKBOX_VENV:-$REPO_ROOT/.venv}"
DATA_DIR="${BLACKBOX_DATA_DIR:-$REPO_ROOT/.local-data}"

say() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
die() { printf '\n\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- 0. sanity checks
case "$(hostname)" in
  scc[0-9]|scc[0-9].bu.edu|geo|geo.bu.edu) die "You are on an SCC login node ($(hostname)). Start an OnDemand VS Code or Desktop session and run this there." ;;
esac

# ---------------------------------------------------------------- 1. python venv
supported() { "$1" -c 'import sys; sys.exit(0 if sys.version_info[:2] in ((3, 11), (3, 12)) else 1)' 2>/dev/null; }

if [ ! -x "$VENV/bin/python" ]; then
  PY="${PYTHON:-}"
  if [ -z "$PY" ]; then
    for cand in python3.12 python3.11 python3; do
      if command -v "$cand" >/dev/null 2>&1 && supported "$(command -v "$cand")"; then
        PY="$(command -v "$cand")"; break
      fi
    done
  fi
  [ -n "$PY" ] && supported "$PY" || die "Need Python 3.11 or 3.12 (found: $(python3 --version 2>&1)).
  On SCC run:   module avail python3     then e.g.   module load python3/3.12.4
  and re-run:   make setup-scc"
  say "Creating Python venv at $VENV with $("$PY" --version)"
  "$PY" -m venv --prompt agent-blackbox "$VENV"
else
  say "Python venv already exists at $VENV ($("$VENV/bin/python" --version))"
fi
supported "$VENV/bin/python" || die "$VENV uses an unsupported Python. Delete it (rm -rf $VENV) and re-run with Python 3.11/3.12."
export PATH="$VENV/bin:$PATH"

# ---------------------------------------------------------------- 2. python deps + services
say "Installing API + Postgres/Redis/Node wheels (pip)"
python -m pip install --quiet --upgrade pip
python -m pip install --quiet -e "apps/api[dev]" -r infra/scc/requirements-local-services.txt

say "Linking Postgres binaries into $VENV/bin"
PG_BIN="$(python -c 'import pathlib, pgserver; print(pathlib.Path(pgserver.__file__).parent / "pginstall" / "bin")' 2>/dev/null)"
[ -x "$PG_BIN/pg_ctl" ] || die "pgserver installed but $PG_BIN/pg_ctl not found"
for bin in initdb pg_ctl postgres psql createdb pg_isready pg_dump; do
  ln -sf "$PG_BIN/$bin" "$VENV/bin/$bin"
done

for bin in initdb pg_ctl psql createdb redis-server redis-cli node npm npx; do
  command -v "$bin" >/dev/null 2>&1 || die "'$bin' missing from $VENV/bin"
done
echo "postgres $(postgres --version | awk '{print $3}'), redis $(redis-server --version | awk '{print $3}' | cut -d= -f2), node $(node --version)"

# ---------------------------------------------------------------- 3. web deps
say "Installing web dependencies (npm ci)"
(cd apps/web && npm ci --no-audit --no-fund)

# ---------------------------------------------------------------- 4. .env
rand() { python -c 'import secrets; print(secrets.token_urlsafe(24))'; }

if [ ! -f "$ENV_FILE" ]; then
  say "Writing $ENV_FILE with random passwords and per-user ports"
  # Spread users across 20000-59990 so two people on one node don't collide.
  BASE=$(( 20000 + ( $(id -u) % 4000 ) * 10 ))
  PG_PASSWORD="$(rand)"
  REDIS_PASSWORD="$(rand)"
  umask 077
  cat > "$ENV_FILE" <<EOF
# Generated by infra/scc/setup_scc.sh on $(date -Iseconds). Never commit this file.
ENVIRONMENT=development
BLACKBOX_DATA_DIR=$DATA_DIR
BLACKBOX_VENV=$VENV
PG_PORT=$BASE
PG_USER=blackbox
PG_PASSWORD=$PG_PASSWORD
PG_DATABASE=blackbox
REDIS_PORT=$((BASE + 1))
REDIS_PASSWORD=$REDIS_PASSWORD
API_PORT=$((BASE + 2))
WEB_PORT=$((BASE + 3))
DATABASE_URL=postgresql+psycopg://blackbox:$PG_PASSWORD@127.0.0.1:$BASE/blackbox
REDIS_URL=redis://:$REDIS_PASSWORD@127.0.0.1:$((BASE + 1))/0
API_INTERNAL_URL=http://127.0.0.1:$((BASE + 2))
CORS_ORIGINS=http://127.0.0.1:$((BASE + 3)),http://localhost:$((BASE + 3))
EOF
  umask 022
else
  say ".env already exists; keeping it"
  grep -q '^BLACKBOX_VENV=' "$ENV_FILE" || echo "BLACKBOX_VENV=$VENV" >> "$ENV_FILE"
fi
chmod 600 "$ENV_FILE"

# ---------------------------------------------------------------- 5. postgres cluster
set -a; # shellcheck disable=SC1090
source "$ENV_FILE"; set +a

mkdir -p "$DATA_DIR"
chmod 700 "$DATA_DIR"
if [ ! -f "$DATA_DIR/postgres/PG_VERSION" ]; then
  say "Initialising Postgres cluster in $DATA_DIR/postgres"
  PWFILE="$(mktemp)"
  printf '%s\n' "$PG_PASSWORD" > "$PWFILE"
  initdb -D "$DATA_DIR/postgres" -U "$PG_USER" --auth=scram-sha-256 --pwfile="$PWFILE" \
    --encoding=UTF8 --no-locale >/dev/null
  rm -f "$PWFILE"
else
  say "Postgres cluster already initialised"
fi

bash "$REPO_ROOT/infra/scc/services.sh" start

if ! PGPASSWORD="$PG_PASSWORD" psql -h 127.0.0.1 -p "$PG_PORT" -U "$PG_USER" -d postgres -tAc \
     "SELECT 1 FROM pg_database WHERE datname='$PG_DATABASE'" | grep -q 1; then
  say "Creating database $PG_DATABASE"
  PGPASSWORD="$PG_PASSWORD" createdb -h 127.0.0.1 -p "$PG_PORT" -U "$PG_USER" "$PG_DATABASE"
fi

say "Applying migrations"
(cd apps/api && python -m alembic upgrade head)

say "Setup complete.
  Activate the venv:   source $VENV/bin/activate
  Run everything:      make dev"
